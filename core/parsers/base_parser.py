#!/usr/bin/env python3
"""
NexusForensics Mobile™ | Base Artifact Parser Contract
Zimmerman-philosophy: many small, focused, single-purpose parsers with first-class lineage.
Enforces the NEXUS Common Parser Contract: Hot-swappable parsers, deterministic output,
provenance enforcement, entity extraction, and self-validating testability.
"""

from abc import ABC, abstractmethod
from pathlib import Path
from typing import List, Tuple, Dict, Any, Optional
import uuid
import hashlib
import inspect
import time

from ..models import (
    ArtifactModel,
    EventModel,
    EntityModel,
    RelationshipModel,
    ParserModel,
    ParserMetadata,
    ParserContext,
    EvidenceSourceModel,
    ParseOutput,
    ParseManifestModel,
    validate_parse_output
)

class BaseArtifactParser(ABC):
    """
    Abstract contract for artifact parsers.
    Parses an evidence source file and yields immutable artifacts, normalized timeline events,
    extracted graph entities, and correlated relationships.
    Every parser provides deterministic UUID, version, git commit, and SHA-256 hash.
    """

    @property
    @abstractmethod
    def parser_name(self) -> str:
        """Unique canonical identifier of the parser."""
        pass

    @property
    @abstractmethod
    def artifact_type(self) -> str:
        """Type of primary artifact generated by this parser."""
        pass

    @property
    def parser_version(self) -> str:
        return "1.0.0"

    @property
    def parser_id(self) -> str:
        return str(uuid.uuid5(uuid.NAMESPACE_DNS, f"nexus.parser.{self.parser_name}.{self.parser_version}"))

    @property
    def parser_sha256(self) -> str:
        try:
            src = inspect.getsource(self.__class__).encode("utf-8")
            return hashlib.sha256(src).hexdigest()
        except Exception:
            return hashlib.sha256(self.parser_name.encode("utf-8")).hexdigest()

    @property
    def developer(self) -> str:
        return "NEXUS Mobile DFIR Team"

    @property
    def git_commit(self) -> str:
        return "9f7c8e2"

    @property
    def build_number(self) -> str:
        return "2026.10.1"

    @property
    def release_date(self) -> str:
        return "2026-10-09 00:00:00"

    @property
    def supported_platforms(self) -> List[str]:
        return ["android", "ios"]

    @property
    def supported_artifact_types(self) -> List[str]:
        return [self.artifact_type]

    def metadata(self) -> ParserMetadata:
        """Returns strongly-typed metadata descriptor for this parser."""
        return ParserMetadata(
            parser_id=self.parser_id,
            parser_name=self.parser_name,
            parser_version=self.parser_version,
            git_commit=self.git_commit,
            build_number=self.build_number,
            release_date=self.release_date,
            parser_sha256=self.parser_sha256,
            developer=self.developer,
            author=self.developer,
            supported_platforms=self.supported_platforms,
            supported_artifact_types=self.supported_artifact_types,
            active=True
        )

    def validate_source(self, source: EvidenceSourceModel) -> bool:
        """Validates that the physical evidence file exists and matches its registered SHA-256."""
        path = Path(source.original_path or source.original_filename)
        if not path.exists():
            return False
        computed_sha = hashlib.sha256(path.read_bytes()).hexdigest()
        return computed_sha == source.sha256

    @abstractmethod
    def can_parse(self, file_path: Path) -> bool:
        """Determines if this parser is capable of parsing the target file."""
        pass

    @abstractmethod
    def parse(self, file_path: Path, source_id: str, device_id: str) -> List[Tuple[ArtifactModel, List[EventModel]]]:
        """Legacy / standard entrypoint yielding (ArtifactModel, List[EventModel])."""
        pass

    def parse_output(self, file_path: Path, source_id: str, device_id: str) -> ParseOutput:
        """
        NEXUS Common Parser Contract entrypoint.
        Emits strongly-typed ParseOutput containing artifacts, events, entities, and relationships.
        Default implementation delegates to parse() and normalizes output.
        """
        pairs = self.parse(file_path, source_id, device_id)
        artifacts: List[ArtifactModel] = []
        events: List[EventModel] = []
        for art, evs in pairs:
            artifacts.append(art)
            events.extend(evs)
        
        output = ParseOutput(
            artifacts=artifacts,
            events=events,
            entities=[],
            relationships=[]
        )
        return output
